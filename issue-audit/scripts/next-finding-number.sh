#!/usr/bin/env bash
#
# next-finding-number.sh — 재감사의 다음 발견 번호를 결정적으로 산출한다.
#
# SKILL.md "발견 번호 계승"은 다음 번호를 "보존된 모든 리포트의 발견 번호와
# 리포트 머리말에 명시된 번호 기준선 중 최대값 + 1"로 정한다. 손으로 세면
# 한 번호를 건너뛰거나(기준선에 다음 번호를 적는 실수) 회차마다 재사용하기 쉬워
# 잔여분이 새 문제처럼 보이므로, 계산을 명령으로 옮긴다.
#
# 기준선 줄과 본문 발견 번호를 구분하지 않고 `F-<숫자>` 를 모두 모아 최대값을 잡는다.
# 기준선의 의미가 "마지막 사용·예약 번호"라 본문 번호와 같은 축이기 때문이다.
# 템플릿 자리표시자(`F-n`, `F-<번호>`)는 숫자가 아니라 매칭되지 않는다.
#
# 사용법:
#   next-finding-number.sh [<리포트 파일>...]
#
# 인자가 없거나 어느 파일에도 발견 번호가 없으면 1 을 출력한다 (초회 감사).
# 발견 0건 회차가 끼어도 그 이전 회차의 최대 번호가 그대로 유지된다.
#
# 종료 코드: 0 산출 성공 / 2 사용오류(읽을 수 없는 경로)

set -o pipefail

usage() { sed -n '3,20p' "$0" | sed 's/^# \{0,1\}//'; }

files=()
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    -*) echo "error: 알 수 없는 옵션 — $1" >&2; exit 2 ;;
    *) files+=("$1"); shift ;;
  esac
done

# 존재하지 않는 경로는 조용히 넘기지 않는다 — 경로 오타를 초회 감사(1)로 오인하면
# 이미 쌓인 번호를 통째로 재사용하게 된다. "리포트가 아직 없음"은 인자 0개로 표현한다.
for f in ${files+"${files[@]}"}; do
  [ -r "$f" ] || { echo "error: 읽을 수 없는 파일 — $f" >&2; exit 2; }
done

if [ ${#files[@]} -eq 0 ]; then
  echo 1
  exit 0
fi

max="$(grep -ohE 'F-[0-9]+' "${files[@]}" 2>/dev/null \
  | sed 's/^F-//' \
  | sed 's/^0*\([0-9]\)/\1/' \
  | sort -n \
  | tail -1)"

if [ -z "$max" ]; then
  echo 1
else
  echo $((max + 1))
fi
